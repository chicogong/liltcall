export function resolveLocale(saved: string | null, browserLanguage: string): Locale {
  if (saved === "en" || saved === "zh-CN") return saved;
  return browserLanguage.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(locale: Locale, key: CopyKey, values: Record<string, string | number> = {}): string {
  const template = locale === "zh-CN" ? zhCN[key] : en[key];
  return template.replace(/\{([a-zA-Z]+)\}/g, (match, name: string) => String(values[name] ?? match));
}
